"""Compile the image-generated atlas into registered raster animation frames.

Requires Pillow. Normal app/CI builds use the committed outputs, not Python.
"""
import json
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'artwork/firefly'
OUTPUT = ROOT / 'web/assets'
SIZE = 256
sheet = Image.open(SOURCE / 'atlas-source.png').convert('RGBA')
alpha = sheet.getchannel('A')


def boundaries(length, horizontal):
    cuts = [0]
    for division in range(1, 4):
        expected = length * division / 4
        radius = round(length / 4 * .16)
        samples = []
        for coordinate in range(round(expected)-radius, round(expected)+radius+1):
            strip = (alpha.crop((0, coordinate, sheet.width, coordinate+1)) if horizontal
                     else alpha.crop((coordinate, 0, coordinate+1, sheet.height)))
            histogram = strip.histogram()
            ink = sum(count * value for value, count in enumerate(histogram) if value >= 16)
            samples.append((ink, abs(coordinate-expected), coordinate))
        cuts.append(min(samples)[2])
    return cuts + [length]


xs, ys = boundaries(sheet.width, False), boundaries(sheet.height, True)
scale = (SIZE-40) / max(max(b-a for a, b in zip(xs, xs[1:])), max(b-a for a, b in zip(ys, ys[1:])))
frames = []
for row in range(4):
    for column in range(4):
        tile = sheet.crop((xs[column], ys[row], xs[column+1], ys[row+1]))
        tile = tile.resize((round(tile.width*scale), round(tile.height*scale)), Image.Resampling.LANCZOS)
        frame = Image.new('RGBA', (SIZE, SIZE))
        frame.alpha_composite(tile, ((SIZE-tile.width)//2, (SIZE-tile.height)//2))
        frames.append(frame)


def head_anchor(frame):
    pixels = frame.load()
    x_total = y_total = weight_total = 0
    for y in range(SIZE):
        for x in range(SIZE):
            r, g, b, a = pixels[x, y]
            if a > 100 and r > 110 and r-g > 35 and r > b*1.5:
                weight = (r-g)**2
                x_total += x*weight
                y_total += y*weight
                weight_total += weight
    return (x_total/weight_total, y_total/weight_total)


# Wing poses share the resting head position; emergence frames retain their
# deliberately changing positions behind/above the illustrated bush.
anchor = head_anchor(frames[7])
for index in range(8):
    current = head_anchor(frames[index])
    registered = Image.new('RGBA', (SIZE, SIZE))
    registered.alpha_composite(frames[index], (round(anchor[0]-current[0]), round(anchor[1]-current[1])))
    frames[index] = registered

animations = {
    'idle': {'frames': [7, 0, 1, 2, 3, 4, 3, 4, 3, 4, 5, 6, 7],
             'durations': [120, 80, 80, 65, 65, 65, 65, 65, 65, 65, 80, 100, 120]},
    'found': {'frames': [8, 9, 10, 11, 12, 13, 12, 13, 12, 13, 14, 7],
              'durations': [110, 110, 110, 90, 70, 70, 70, 70, 70, 70, 100, 160]}
}
OUTPUT.mkdir(exist_ok=True)
atlas = Image.new('RGBA', (SIZE*4, SIZE*4))
for index, frame in enumerate(frames):
    atlas.alpha_composite(frame, ((index % 4)*SIZE, (index // 4)*SIZE))
atlas.save(OUTPUT / 'firefly-atlas.png', optimize=True)
frames[7].save(OUTPUT / 'firefly.png', optimize=True)
manifest = {'size': SIZE, 'columns': 4, 'rest': 7, 'animations': animations}
(ROOT / 'web/firefly-frames.js').write_text('// Generated by scripts/build-firefly-sprites.py.\nexport const fireflyFrames='+json.dumps(manifest, separators=(',', ':'))+';\n', encoding='utf-8')

for kind, animation in animations.items():
    selected = [frames[index] for index in animation['frames']]
    selected[0].save(SOURCE / (kind+'-preview.webp'), save_all=True, append_images=selected[1:], duration=animation['durations'], loop=0, lossless=True)

contact = Image.new('RGB', (SIZE*4, (SIZE+24)*4), '#dfe7dc')
draw = ImageDraw.Draw(contact)
for index, frame in enumerate(frames):
    x, y = (index % 4)*SIZE, (index // 4)*(SIZE+24)
    contact.paste(frame, (x, y), frame)
    draw.text((x+8, y+SIZE+5), str(index), fill='#234536')
(ROOT / 'artifacts').mkdir(exist_ok=True)
contact.save(ROOT / 'artifacts/firefly-frame-contact.png')
print(json.dumps({'cuts': {'x': xs, 'y': ys}, 'size': SIZE, 'durations': {key: sum(value['durations']) for key, value in animations.items()}}))
