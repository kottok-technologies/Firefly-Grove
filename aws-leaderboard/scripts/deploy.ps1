param(
  [string]$Profile = 'default',
  [string]$Region = 'us-east-1',
  [ValidatePattern('^[a-zA-Z][a-zA-Z0-9-]{0,70}$')][string]$StackName = 'firefly-grove-leaderboard',
  [switch]$ReviewOnly
)
$ErrorActionPreference = 'Stop'
$projectRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$workspaceRoot = [IO.Path]::GetFullPath((Join-Path $projectRoot '..'))
function Invoke-AwsCommand {
  param([string[]]$Arguments)
  $result = & aws @Arguments --profile $Profile --region $Region --no-cli-pager
  if ($LASTEXITCODE -ne 0) { throw "AWS command failed: $($Arguments[0]) $($Arguments[1])" }
  return $result
}
# Authentication happens through the AWS CLI. Never supply keys in this script.
Invoke-AwsCommand -Arguments @('sts','get-caller-identity','--query','Arn','--output','text')
Push-Location $projectRoot
try {
  & npm run build
  if ($LASTEXITCODE -ne 0) { throw 'Lambda build failed' }
  $zipPath = Join-Path $projectRoot 'dist/lambda.zip'
  Compress-Archive -LiteralPath (Join-Path $projectRoot 'dist/handler.mjs') -DestinationPath $zipPath -Force
  $digest = (Get-FileHash -LiteralPath $zipPath -Algorithm SHA256).Hash.ToLowerInvariant()
  $artifactStack = "$StackName-artifacts"
  Invoke-AwsCommand -Arguments @('cloudformation','deploy','--stack-name',$artifactStack,'--template-file',(Join-Path $projectRoot 'artifacts-template.json'),'--no-fail-on-empty-changeset')
  $bucket = (Invoke-AwsCommand -Arguments @('cloudformation','describe-stacks','--stack-name',$artifactStack,'--query',"Stacks[0].Outputs[?OutputKey=='BucketName'].OutputValue | [0]",'--output','text')).Trim()
  $codeKey = "lambda/$digest.zip"
  Invoke-AwsCommand -Arguments @('s3','cp',$zipPath,"s3://$bucket/$codeKey",'--only-show-errors')
  Invoke-AwsCommand -Arguments @('cloudformation','validate-template','--template-body',('file://'+(Join-Path $projectRoot 'template.json')))
  $deployArguments = @('cloudformation','deploy','--stack-name',$StackName,'--template-file',(Join-Path $projectRoot 'template.json'),'--capabilities','CAPABILITY_IAM','--parameter-overrides',"CodeBucket=$bucket","CodeKey=$codeKey",'--no-fail-on-empty-changeset')
  if ($ReviewOnly) { $deployArguments += '--no-execute-changeset' }
  Invoke-AwsCommand -Arguments $deployArguments
  if ($ReviewOnly) { Write-Output 'Change set prepared. Infrastructure has not been executed; the private artifact bucket has been created.'; return }
  $origin = (Invoke-AwsCommand -Arguments @('cloudformation','describe-stacks','--stack-name',$StackName,'--query',"Stacks[0].Outputs[?OutputKey=='ApiUrl'].OutputValue | [0]",'--output','text')).Trim()
  if ($origin -notmatch '^https://[a-z0-9]+\.execute-api\.[a-z0-9-]+\.amazonaws\.com$') { throw 'Unexpected API endpoint; app configuration was not updated' }
  $health = Invoke-RestMethod -Uri "$origin/api/v1/health"
  if (!$health.ok -or $health.provider -ne 'aws') { throw 'Deployed API health check failed' }
  $publicBoard = Invoke-RestMethod -Uri "$origin/api/v1/leaderboard"
  if ($null -eq $publicBoard.entries) { throw 'Deployed leaderboard read failed' }
  $settings = @{ origin = $origin } | ConvertTo-Json -Compress
  $config = "// Generated by the AWS deployment script. Public endpoint only; no credentials.`nexport const leaderboardConfig=$settings;`n"
  [IO.File]::WriteAllText((Join-Path $workspaceRoot 'web/leaderboard-config.js'),$config,[Text.UTF8Encoding]::new($false))
  Write-Output "Leaderboard is live: $origin"
  Write-Output 'App endpoint updated. Build a new APK to include it.'
} finally { Pop-Location }
